#!/usr/bin/env python3
"""Writes sections/numbers.tex: the numbers of Section 6 that change while runs come in, from results/ only.
Run scripts/breakeven.py first."""
import glob, json

R = 'results/'
be = json.load(open(f'{R}rq1/localsend/break-even.json'))
repairs = [json.load(open(f)) for f in sorted(glob.glob(f'{R}rq3/localsend/repair-*.json'))]

def ordinal(n):
    return f'{n}\\textsuperscript{{{"th" if 10 <= n % 100 <= 20 else {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")}}}'

def cls(c):
    fs = [f for f in repairs if f['mutant'].startswith(c)]
    att = [a for f in fs for a in f['attempts']]
    div = sum(len(f['traces_diverged_in_this_run']) for f in fs)
    acc = sum(len(f['traces_repaired']) for f in fs)
    none = sum(1 for a in att if a['refusal_reason'] == 'no_proposal')
    return fs, att, div, acc, none

d4f, d4a, d4div, d4acc, d4none = cls('d4')
d6f, d6a, d6div, d6acc, d6none = cls('d6')
mins = round(be['repair_seconds_per_trace'] / 60)
hand = [r for f in sorted(glob.glob(f'{R}rq3/localsend/hand-*.json')) for r in json.load(open(f))['traces']]
d6runs = [json.load(open(f)) for f in glob.glob(f'{R}rq1/localsend/rerun-d6-*.json')]
macros = {
    'HANDtraces': str(len(hand)),
    'DSIXgoal': f"{sum(t['reached_goal'] for f in d6runs for t in f['traces'])} of {len(d6runs)}",
    'BEprice': ordinal(be['break_even_price']), 'BEtime': ordinal(be['break_even_time']),
    'BEpriceX': ordinal(be['break_even_price_with_new_explorations']), 'BEtimeX': ordinal(be['break_even_time_with_new_explorations']),
    'BEreprice': f"\\${be['repair_price_usd_per_trace']:.2f}", 'BEresec': f'{mins}~min',
    'BEunrepaired': str(be['unrepaired_trace_mutant_pairs_not_d6']),
    'BErepairprice': f"\\${sum(f['proposer_price_usd'] for f in repairs):.2f}",
    'BEdfournone': str(d4none), 'BEdfourattempts': str(len(d4a)),
    'CellDfour': f'{d4acc} of {d4div} traces; no action proposed in {d4none} of {len(d4a)} attempts',
    'CellDsix': f'{sum(1 for a in d6a if a["accepted"])} of {len(d6a)} attempts; no false green',
}
with open('sections/numbers.tex', 'w') as out:
    out.write('% Generated by scripts/tex_numbers.py from paper/results/. Do not edit.\n')
    for k, v in macros.items():
        out.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')
print(open('sections/numbers.tex').read())

# French review copy: the same numbers, in French
def fr_ord(n):
    return f'{n}\\textsuperscript{{{"er" if n == 1 else "e"}}}'
def usd_fr(x):
    return f'{x:.2f}'.replace('.', ',') + '~\\$'
fr = dict(macros)
fr.update({
    'BEprice': fr_ord(be['break_even_price']), 'BEtime': fr_ord(be['break_even_time']),
    'BEpriceX': fr_ord(be['break_even_price_with_new_explorations']), 'BEtimeX': fr_ord(be['break_even_time_with_new_explorations']),
    'BEreprice': usd_fr(be['repair_price_usd_per_trace']),
    'BErepairprice': usd_fr(sum(f['proposer_price_usd'] for f in repairs)),
    'CellDfour': f'{d4acc} sur {d4div} traces ; aucune action proposée dans {d4none} tentatives sur {len(d4a)}',
    'CellDsix': f'{sum(1 for a in d6a if a["accepted"])} tentative acceptée sur {len(d6a)} ; aucun faux vert',
    'DSIXgoal': f"{sum(t['reached_goal'] for f in d6runs for t in f['traces'])} sur {len(d6runs)}",
})
with open('sections/numbers-fr.tex', 'w') as out:
    out.write('% Generated by scripts/tex_numbers.py from paper/results/, for the French review copy. Do not edit.\n')
    for k, v in fr.items():
        out.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')
